import math
def somar(a,b):
    soma = a + b
    return soma

def multiplicar(a, b):
    multi = a * b
    return  multi

def dividir(a,b):
    div = a / b
    return  div

def subtrair(a, b):
    sub = a - b
    return  sub

def sqrroot(a):
    sqr = math.sqrt(a)
    return sqr

def exp(a, b):
    expo = a ^ b
    return expo